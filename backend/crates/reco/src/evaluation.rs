//! Paired radio evaluation on one immutable snapshot and listener profile.

use std::collections::HashSet;

use serde::Serialize;
use uuid::Uuid;

use crate::radio::{self, Features, Focus, RadioRequest, Ranking};
use crate::rules::Verdict;
use crate::{Listener, Snapshot, taste, vector};

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Distribution {
    pub count: usize,
    pub min: f32,
    pub p10: f32,
    pub median: f32,
    pub p90: f32,
    pub max: f32,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Pick {
    pub track_id: Uuid,
    pub score: f32,
    pub explore: bool,
    pub features: Features,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Variant {
    pub ranking: Ranking,
    pub picks: Vec<Pick>,
    pub mean_seed_similarity: f32,
    pub mean_pair_similarity: f32,
    pub artist_count: usize,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Case {
    pub seed_track_id: Uuid,
    pub similarity: Distribution,
    pub variants: [Variant; 2],
}

/// Starts with a strongly preferred track, then spreads seeds across the sound
/// space. This is a coverage sample, not an estimate of the listening distribution.
pub fn seeds(snapshot: &Snapshot, listener: &Listener, count: usize) -> Vec<Uuid> {
    let eligible: Vec<usize> = (0..snapshot.len()).filter(|&row| allowed(snapshot, listener, row)).collect();
    let Some(first) = eligible.iter().copied().max_by(|&a, &b| {
        let score = |row| listener.tracks.get(&snapshot.meta(row).track_id).map_or(0.0, |s| s.score);
        score(a).total_cmp(&score(b)).then(b.cmp(&a))
    }) else {
        return vec![];
    };
    let mut result = Vec::new();
    let mut taken = HashSet::new();
    let mut nearest = vec![f32::NEG_INFINITY; snapshot.len()];
    let mut next = Some(first);
    while result.len() < count {
        let Some(row) = next else { break };
        result.push(snapshot.meta(row).track_id);
        taken.extend(snapshot.clones(row));
        for &other in &eligible {
            nearest[other] = nearest[other].max(snapshot.between(row, other));
        }
        next = eligible
            .iter()
            .copied()
            .filter(|row| !taken.contains(row))
            .min_by(|&a, &b| nearest[a].total_cmp(&nearest[b]).then(a.cmp(&b)));
    }
    result
}

fn allowed(snapshot: &Snapshot, listener: &Listener, row: usize) -> bool {
    let meta = snapshot.meta(row);
    listener.rules.verdict(meta) != Verdict::Blocked
        && listener.tracks.get(&meta.track_id).is_none_or(|s| !s.rejected())
}

/// Both paths see the same history, candidates, clock, and random seed. No
/// artificial playback, impressions or feedback are generated by evaluation.
pub fn compare(snapshot: &Snapshot, listener: &Listener, seeds: &[Uuid]) -> Vec<Case> {
    let taste = taste::taste(snapshot, listener);
    seeds
        .iter()
        .filter_map(|&seed| {
            let row = snapshot.row_of(seed)?;
            let clones = snapshot.clones(row);
            let scores: Vec<f32> = snapshot
                .similarities(snapshot.vector(row))
                .into_iter()
                .enumerate()
                .filter(|(other, score)| {
                    !clones.contains(other) && score.is_finite() && allowed(snapshot, listener, *other)
                })
                .map(|(_, score)| score)
                .collect();
            let similarity = Distribution {
                count: scores.len(),
                min: vector::quantile(&scores, 0.0),
                p10: vector::quantile(&scores, 0.1),
                median: vector::quantile(&scores, 0.5),
                p90: vector::quantile(&scores, 0.9),
                max: vector::quantile(&scores, 1.0),
            };
            let request = RadioRequest {
                seed: Some(seed),
                queue: &[],
                recent: &[],
                session: None,
                limit: 10,
                focus: Focus::Balanced,
            };
            let variants = [Ranking::LegacyV3, Ranking::CalibratedV4].map(|ranking| {
                let batch = radio::next_with_ranking(snapshot, listener, &taste, &request, ranking);
                let mut pairs = Vec::new();
                for (index, pick) in batch.picks.iter().enumerate() {
                    for previous in &batch.picks[..index] {
                        pairs.push(snapshot.between(previous.row, pick.row));
                    }
                }
                let artists: HashSet<Uuid> = batch.picks.iter().map(|p| snapshot.meta(p.row).artist()).collect();
                let cosines: Vec<f32> = batch.picks.iter().map(|p| p.features.similarity).collect();
                Variant {
                    ranking,
                    mean_seed_similarity: mean(&cosines),
                    mean_pair_similarity: mean(&pairs),
                    artist_count: artists.len(),
                    picks: batch
                        .picks
                        .iter()
                        .map(|pick| Pick {
                            track_id: snapshot.meta(pick.row).track_id,
                            score: pick.score,
                            explore: pick.explore,
                            features: pick.features,
                        })
                        .collect(),
                }
            });
            Some(Case { seed_track_id: seed, similarity, variants })
        })
        .collect()
}

fn mean(values: &[f32]) -> f32 {
    #[expect(clippy::cast_precision_loss, reason = "at most 45 pairs in a top ten")]
    let count = values.len().max(1) as f32;
    values.iter().sum::<f32>() / count
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::snapshot::tests::snapshot;

    #[test]
    fn coverage_sampling_is_stable_spread_and_respects_blocks() {
        let snapshot = snapshot(&[
            (1, 10, "a", [1.0, 0.0, 0.0]),
            (2, 20, "b", [0.9, 0.1, 0.0]),
            (3, 30, "c", [0.0, 1.0, 0.0]),
            (4, 40, "d", [0.0, 0.0, 1.0]),
        ]);
        let listener = Listener { rules: crate::rules::Rules::new([Uuid::from_u128(40)], []), ..Listener::default() };
        assert_eq!(seeds(&snapshot, &listener, 2), vec![Uuid::from_u128(1), Uuid::from_u128(3)]);
        assert_eq!(seeds(&snapshot, &listener, 10).len(), 3);
        assert!(seeds(&snapshot, &listener, 0).is_empty());
    }

    #[test]
    fn paired_comparison_is_reproducible_and_preserves_raw_diagnostics() {
        let snapshot =
            snapshot(&[(1, 10, "a", [1.0, 0.0, 0.0]), (2, 20, "b", [0.9, 0.1, 0.0]), (3, 30, "c", [0.0, 1.0, 0.0])]);
        let listener = Listener::default();
        let seeds = seeds(&snapshot, &listener, 2);
        let cases = compare(&snapshot, &listener, &seeds);
        assert_eq!(
            serde_json::to_value(&cases).unwrap(),
            serde_json::to_value(compare(&snapshot, &listener, &seeds)).unwrap()
        );
        assert_eq!(cases[0].similarity.count, 2);
        assert!(cases[0].variants[0].picks.iter().all(|p| p.features.similarity_rank.is_none()));
        assert!(cases[0].variants[1].picks.iter().all(|p| p.features.similarity_rank.is_some()));
    }
}
