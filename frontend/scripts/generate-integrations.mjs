import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

export function generateIntegrations() {
  const root = new URL("../src/integrations/", import.meta.url);
  const manifests = readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .flatMap(({ name }) => {
      const path = new URL(`${name}/manifest.json`, root);
      if (!existsSync(path)) return [];
      const { id, order = 0 } = JSON.parse(readFileSync(path, "utf8"));
      if (!/^[a-z][a-z0-9-]*$/.test(name) || id !== name || !Number.isInteger(order)) {
        throw new Error(`Invalid integration manifest in ${name}`);
      }
      return [{ id, order }];
    })
    .sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));

  const imports = manifests.map(
    ({ id }, index) => `import { integration as module${index} } from "./${id}";`,
  );
  const entries = manifests.map(({ id }, index) => `  { ...module${index}, id: "${id}" },`);
  const source = [
    "// SPDX-License-Identifier: AGPL-3.0-only",
    "// Generated by scripts/generate-integrations.mjs.",
    'import type { Integration } from "./types";',
    ...imports,
    "",
    "export const integrations: readonly Integration[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");

  const target = new URL("generated.ts", root);
  if (!existsSync(target) || readFileSync(target, "utf8") !== source) {
    writeFileSync(target, source);
  }
}
